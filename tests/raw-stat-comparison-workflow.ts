import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {assembleReferenceData,type CourseReference} from '../src/data/reference';
import {adjustedRawStats,projectRawStats,compareRawStats,type RawStatProfile,type RawContext} from '../src/data/raw-stat-comparison';
import {activationConfidence} from '../src/sandbox/activation-confidence';
import {meanConfidence} from '../src/sandbox/mean-confidence';
import {distribution} from '../src/sandbox/results';

const profile:RawStatProfile={id:'a',name:'Reference',stats:{speed:1200,stamina:1200,power:1000,guts:600,wisdom:1000},distance:7,surface:7,strategyAptitude:7,strategy:2,mood:3};
const course:CourseReference={id:1,name:'Flat fixture',trackName:'Fixture',raceTrackId:1,distance:2000,surface:1,turn:1,course:1,laneMax:1,courseSetStatus:[],corners:[],straights:[],slopes:[],source:{name:'synthetic',revision:'test',url:''},geometry:'segment-schematic'};
const ctx:RawContext={course,ground:1,strategy:2,mood:3};
const changed=(key:keyof RawStatProfile['stats'],value:number)=>({...profile,stats:{...profile.stats,[key]:value}});
const flat=projectRawStats(profile,ctx);
assert.equal(flat.initialHp,2000+.8*.89*1200);
const term=Math.sqrt(500*1200)*.002;
assert.equal(flat.maxSpurt,(20*.975+term+.2)*1.05+term+(450*600)**.597*.0001);
assert.equal(flat.downTime,0);assert.equal(flat.downGain,0);assert.equal(flat.carry,0);
assert(flat.time>85&&flat.time<110);
assert.equal(flat.spurtStart,2000*2/3);
assert.deepEqual(compareRawStats(profile,profile,ctx).left.total,{time:0,distance:0,spurtSpeed:0});
assert(projectRawStats(changed('speed',1300),ctx).time<flat.time,'Speed improves an adequately fueled flat race');
assert(projectRawStats(changed('power',1100),ctx).time<flat.time,'Power improves acceleration');
assert(projectRawStats({...profile,distance:8},ctx).time<flat.time,'Distance S increases late speed');
assert(projectRawStats({...profile,surface:8},ctx).time<flat.time,'Surface S improves acceleration');
assert.equal(adjustedRawStats(changed('speed',1400),ctx).speed,1300);
assert.equal(adjustedRawStats(profile,{...ctx,mood:5}).speed,1248);
assert.equal(adjustedRawStats(profile,{...ctx,course:{...course,courseSetStatus:[3]}}).speed,1440);
assert.equal(adjustedRawStats({...profile,strategyAptitude:8},ctx).wisdom,1100);
assert.throws(()=>projectRawStats({...profile,distance:null},ctx),/aptitude is missing/);
assert.throws(()=>projectRawStats({...profile,stats:{...profile.stats,speed:null}},ctx),/missing/);
assert.throws(()=>projectRawStats(profile,{...ctx,ground:0}),/known strategy/);
const starved=projectRawStats(changed('stamina',200),ctx);
assert(starved.time>flat.time&&starved.spurtStart>flat.spurtStart,'HP shortage delays or prevents spurt');
const hillCtx={...ctx,course:{...course,slopes:[{start:1200,length:130,slopePercent:2}]}};
assert(projectRawStats(profile,hillCtx).time>flat.time,'Uphill slows the runner');
const downCtx={...ctx,course:{...course,slopes:[{start:1300,length:500,slopePercent:-2}]}};
const down=projectRawStats(profile,downCtx);
assert(down.downTime>10&&down.downTime<25&&down.downGain>0&&down.carry>0,'Downhill occupancy and post-hill momentum retained');
assert(projectRawStats(changed('wisdom',500),downCtx).downTime<down.downTime);
assert(down.time<flat.time);
assert(Math.abs(projectRawStats(profile,downCtx,.05).time-down.time)<.04,'Halving integration step changes finish time by less than 40ms');
const dashA={...profile,stats:{speed:1603,stamina:340,power:1227,guts:605,wisdom:1233},distance:8,surface:8};
const dashB={...profile,stats:{speed:1636,stamina:419,power:1139,guts:801,wisdom:1061}};
const dashContext={...ctx,mood:5,course:{...course,distance:1200,slopes:[{start:100,length:775,slopePercent:-1},{start:875,length:100,slopePercent:2}]}};
const delta=(step:number)=>projectRawStats(dashA,dashContext,step).time-projectRawStats(dashB,dashContext,step).time;
assert(Math.abs(delta(.1)-delta(.01))<.002,'Dash termination cannot invent a step-dependent advantage');
const comparison=compareRawStats(profile,{...profile,stats:{speed:1400,stamina:900,power:1200,guts:800,wisdom:1200},distance:8},hillCtx).left;
assert(Math.abs(comparison.rows.reduce((s,r)=>s+r.distance,comparison.interaction.distance)-comparison.total.distance)<1e-9);
assert.equal(comparison.total.distance,comparison.total.time*comparison.base.finishSpeed);
const otherStyle={...changed('speed',1300),strategy:4,mood:5};
const separate=compareRawStats(profile,otherStyle,ctx);
const aWithBSpeed=projectRawStats(changed('speed',1300),ctx);
assert.equal(separate.left.rows[0].spurtSpeed,flat.maxSpurt-aWithBSpeed.maxSpurt,'A compares its own target against A with B Speed, not B target');
assert(separate.left.rows[0].distance<0&&separate.left.rows[0].time<0,'Lower own Speed is a disadvantage');
assert.equal(separate.right.base.maxSpurt,projectRawStats(otherStyle,{...ctx,strategy:4,mood:5}).maxSpurt,'B retains its own strategy and mood');
const contextOnly=compareRawStats(profile,{...profile,strategy:4,mood:5},ctx);
assert.equal(contextOnly.left.total.distance,0);assert.equal(contextOnly.right.total.distance,0,'Different strategies and moods alone never count as stat advantage');
const mixed={...profile,moods:[{mood:1,weight:1},{mood:5,weight:3}]};
assert.equal(compareRawStats(mixed,profile,ctx).left.base.maxSpurt,projectRawStats(profile,{...ctx,mood:1}).maxSpurt*.25+projectRawStats(profile,{...ctx,mood:5}).maxSpurt*.75);
// Real course geometries: both long hills and multiple separate descents.
const json=(file:string)=>JSON.parse(readFileSync(file,'utf8'));
const ref=assembleReferenceData(json('public/data/metadata.json'),json('public/data/courses.json'),json('public/data/reference-source.json'),json('public/data/simulator-skill-ids.json'));
const courses=Object.values(ref.courses).filter(c=>c.slopes.length>=3).slice(0,4);
for(const track of courses){const estimate=projectRawStats(profile,{...ctx,course:track});assert(Number.isFinite(estimate.time)&&estimate.time>0);assert(estimate.samples.every(p=>Number.isFinite(p.speed)));}

assert.equal(activationConfidence(0,0,5,50),null);
assert.equal(activationConfidence(5,10,8,50,49),null,'Missing skill data cannot support confidence coloring');
assert.equal(activationConfidence(25,50,25,50)?.strength,0);
const uncertain=activationConfidence(13,25,25,50)!;
assert(uncertain.low<0&&uncertain.high>0&&uncertain.strength===0,'A small apparent advantage at 50 races stays neutral');
const strong=activationConfidence(80,100,100,200)!;
assert(strong.low>0&&strong.strength===1);
const inverse=activationConfidence(20,100,100,200)!;
assert(Math.abs(strong.low+inverse.high)<1e-9);
assert(strong.high-strong.low>activationConfidence(800,1000,1000,2000)!.high-activationConfidence(800,1000,1000,2000)!.low);
assert.equal(meanConfidence(distribution([.1])),null);
const mean=meanConfidence(distribution([1,2,3,4,5]))!;
assert(Math.abs(mean.low-1.0367568)<1e-5&&Math.abs(mean.high-4.9632432)<1e-5,'Student-t mean interval matches df4 reference');
console.log('Raw-stat course model and uncertainty calculations passed');

// Dueling is conditional, starts after the proximity warmup and never enters the combined total.
const duelCtx={...ctx,course:{...course,corners:[{start:1200,length:300}],straights:[{start:1500,end:2000}]}};
const plainDuelCourse=projectRawStats(profile,duelCtx);
const duel=projectRawStats(profile,duelCtx,.1,true);
assert(duel.duelTime>10&&duel.time<plainDuelCourse.time);
assert.equal(projectRawStats(profile,ctx,.1,true).duelTime,0,'Cornerless courses cannot duel');
assert.equal(projectRawStats({...profile,stats:{...profile.stats,stamina:1,guts:1,speed:2000}},duelCtx,.1,true).duelTime,0,'Low HP prevents entry');
const duelComparison=compareRawStats(profile,changed('guts',1000),duelCtx).left;
assert(duelComparison.rows.find(r=>r.key==='guts')!.dueling!.distance<0);
assert.equal(duelComparison.total.time,projectRawStats(changed('guts',1000),duelCtx).time-plainDuelCourse.time);
assert.equal(compareRawStats(profile,profile,duelCtx).left.rows.find(r=>r.key==='guts')!.dueling!.distance,0);
assert(Math.abs(projectRawStats(profile,duelCtx,.05,true).time-duel.time)<.02);
